rule((c) => {
  const { me } = c;
  const s = R(c, 'soulsMid');
  const k = R(c, 'kaMid');
  if (!ok(me.soulsMid, s, me.kaMid, k) || k < 2) return null;
  if (me.soulsMid < s * 0.75 && me.kaMid < k * 0.7) {
    return tip('mid_idle', 'mid_role', 'Середина игры', 'bad', 70, 'Простой в середине игры',
      `С 10:00 до 20:00 ты набирал ${N(me.soulsMid)} душ в минуту (топы — ${N(s)}) и участвовал в ${N(me.kaMid)} убийствах (топы — ${N(k)}). Ни фарма, ни драк — время уходило впустую.`,
      'Между драками всегда есть дело: волна на боковой линии, лагерь в лесу, ящики по пути. Если ты стоишь и ждёшь — ты отстаёшь.');
  }
  if (me.soulsMid >= s * 0.95 && me.kaMid < k * 0.6) {
    return tip('mid_solo_farm', 'mid_role', 'Середина игры', 'warn', 55, 'Фармишь много, но без команды',
      `Души в середине игры ты набираешь на уровне топов (${N(me.soulsMid)} в минуту), но в убийствах участвовал ${N(me.kaMid)} ${times(me.kaMid)} против ${N(k)} у топов.`,
      'Фарми ближе к тому месту, где собирается команда, и иди на драку сразу, как она начинается. Души без участия в драках не выигрывают игру.');
  }
  if (me.kaMid >= k && me.soulsMid < s * 0.8) {
    return tip('mid_fight_nofarm', 'mid_role', 'Середина игры', 'warn', 50, 'Много драк, мало фарма',
      `В драках середины игры ты активен (${N(me.kaMid)} убийств и помощи), но душ в минуту ${N(me.soulsMid)} против ${N(s)} у топов.`,
      'После каждой драки не стой на месте: сразу забирай ближайшую волну или лагерь, пока враг возрождается.');
  }
  return null;
});

