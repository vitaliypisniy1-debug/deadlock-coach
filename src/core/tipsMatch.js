rule((c) => {
  const { me } = c;
  if (!ok(me.teamDiff10, me.teamDiff20)) return null;
  if (me.teamDiff10 >= 2500 && me.teamDiff20 <= 0) {
    return tip('mid_lead_lost', 'team_flow', 'Команда', 'warn', 52, 'Команда растеряла преимущество',
      `К 10:00 твоя команда вела на ${N(me.teamDiff10)} душ, а к 20:00 уже ${me.teamDiff20 < 0 ? 'отставала на ' + N(-me.teamDiff20) : 'сравнялась'}.`,
      'Преимущество чаще всего теряют, когда после линий все расходятся по карте. Собирайтесь вместе и давите одну цель.');
  }
  if (me.teamDiff10 <= -2500 && me.teamDiff20 >= 0) {
    return tip('mid_comeback', 'team_flow', 'Команда', 'good', 14, 'Камбэк в середине игры',
      `К 10:00 твоя команда отставала на ${N(-me.teamDiff10)} душ, но к 20:00 вы догнали соперника. Середина игры — твоя сильная сторона в этом матче.`);
  }
  if (me.teamDiff20 !== null && me.teamDiff25 !== null && me.teamDiff25 >= 5000 && !c.won) {
    return tip('late_throw', 'team_flow', 'Команда', 'bad', 72, 'Игра была выиграна к 25:00',
      `К 25:00 твоя команда вела на ${N(me.teamDiff25)} душ — и проиграла.`,
      'С большим преимуществом не нужно гнаться за каждым убийством. Ходите вместе, бейте объекты и не давайте врагу поймать кого-то одного.');
  }
  if (me.teamDiff20 <= -4000 && c.won) {
    return tip('late_comeback', 'team_flow', 'Команда', 'good', 13, 'Вытащили тяжёлую игру',
      `К 20:00 вы отставали на ${N(-me.teamDiff20)} душ, но победили. Такие игры выигрываются терпением — вы не сдались и дождались ошибки врага.`);
  }
  return null;
});

