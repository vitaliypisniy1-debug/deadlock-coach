'use strict';
// Советы по ОДНОЙ игре. Каждое правило смотрит на конкретную ситуацию в матче
// и выбирает вариант текста под неё. Цифры — твои и топов на том же герое.
//
// c = { me, ref, lobby, heroName, itemName, won }
//   me    — признаки твоей игры (features.js)
//   ref   — медианы/квартили тех же признаков у топов на этом герое
//   lobby — то же по остальным игрокам этого матча

const { N, D1, P, T, times, plural, ok, ratio, tip } = require('./tipkit');

const R = (c, k) => (c.ref[k] && c.ref[k].n >= 3 ? c.ref[k].med : null);
const L = (c, k) => (c.lobby[k] && c.lobby[k].n >= 5 ? c.lobby[k].med : null);

const RULES = [];
const rule = (fn) => RULES.push(fn);

// ======================= ЛИНИЯ (0–10) =======================
rule((c) => {
  const { me } = c;
  const ref = R(c, 'lh10');
  if (!ok(me.lh10, ref) || ref < 15 || me.lh10 >= ref * 0.8) return null;
  const sc = 60 + (1 - me.lh10 / ref) * 60;
  const base = `К 10:00 ты добил ${N(me.lh10)} крипов, топы на ${c.heroName(me.hero)} — ${N(ref)}.`;
  if ((me.d10 || 0) === 0) {
    return tip('lane_cs_safe', 'lane_cs', 'Линия', 'warn', sc, 'Безопасная, но бедная линия', `${base} Ты ни разу не умер — значит, мешал не враг, а само добивание.`,
      'Стой ближе к волне и стреляй по крипу, когда у него остаётся мало здоровья. Полных крипов не бей — так волна быстрее уходит к врагу и ты теряешь добивания.');
  }
  if (me.d10 >= 2) {
    return tip('lane_cs_lost', 'lane_cs', 'Линия', 'bad', sc + 15, 'Линия проиграна: мало крипов и смерти', `${base} И ещё ${me.d10} ${plural(me.d10, 'смерть', 'смерти', 'смертей')} до 10:00.`,
      'Когда враг давит, не стой у волны на его стороне. Дай крипам подойти к твоей башне и добивай их там — пережить линию с меньшим фармом лучше, чем умирать.');
  }
  return tip('lane_cs_mid', 'lane_cs', 'Линия', 'warn', sc, 'Мало добитых крипов на линии', `${base} Ты умер один раз — скорее всего, на этом и потерял пару волн.`,
    'Возвращайся на линию к приходу каждой волны. Дорога в лес и обратно часто съедает целую волну крипов.');
});

rule((c) => {
  const { me } = c;
  const ref = R(c, 'soulsPerCreep10');
  const lhRef = R(c, 'lh10');
  if (!ok(me.soulsPerCreep10, ref, me.lh10, lhRef) || me.lh10 < lhRef * 0.85 || me.soulsPerCreep10 >= ref * 0.88) return null;
  return tip('lane_orbs', 'lane_orbs', 'Линия', 'warn', 62, 'Крипов добиваешь, а сферы душ теряешь',
    `К 10:00 на одного добитого крипа у тебя приходится ${D1(me.soulsPerCreep10)} души, у топов — ${D1(ref)}. Добиваешь ты нормально, но часть сфер забирает враг или они пропадают.`,
    'Сразу после добивания стреляй по вылетевшей сфере души — пока её не отобрал враг. Это почти удваивает доход с волны.');
});

rule((c) => {
  const { me } = c;
  const ref = R(c, 'dn10');
  if (!ok(me.dn10, ref) || ref < 4) return null;
  if (me.dn10 < ref * 0.5) {
    return tip('lane_deny_low', 'lane_deny', 'Линия', 'warn', 45, 'Не отбираешь души у врага',
      `К 10:00 у тебя ${N(me.dn10)} отобранных сфер, у топов — ${N(ref)}. Каждая неотобранная сфера — это души твоему противнику.`,
      'Когда враг добивает твоего крипа, стреляй по вылетевшей сфере раньше него. Так ты не только фармишь сам, но и тормозишь его.');
  }
  if (me.dn10 >= ref * 1.5) {
    return tip('lane_deny_good', 'lane_deny', 'Линия', 'good', 12, 'Отлично отбираешь сферы',
      `${N(me.dn10)} отобранных сфер к 10:00 — больше, чем у топов (${N(ref)}). Противник по линии из-за этого фармит меньше.`);
  }
  return null;
});

rule((c) => {
  const { me } = c;
  if (!ok(me.firstDeath)) return null;
  if (me.firstDeath < 180) {
    return tip('death_very_early', 'first_death', 'Линия', 'warn', 55, `Смерть уже на ${T(me.firstDeath)}`,
      'В первые минуты у героев мало здоровья и нечем лечиться, поэтому один неудачный размен уроном сразу превращается в смерть и отданную линию.',
      'В первые 3 минуты не начинай размен первым. Дождись, пока враг потратит способность, и отвечай, когда он не может ответить тем же.');
  }
  if (me.firstDeath < 360 && (me.d10 || 0) >= 1) {
    return tip('death_early_gank', 'first_death', 'Линия', 'warn', 48, `Ранняя смерть на ${T(me.firstDeath)}`,
      'С 3-й по 6-ю минуту враги часто приходят помогать с соседних линий — это самое опасное время на линии.',
      'Если противник с соседней линии пропал с карты — отойди к своей башне, пока он не появится снова.');
  }
  return null;
});

rule((c) => {
  const { me } = c;
  const ref = R(c, 'd10');
  if (!ok(me.d10, ref) || me.d10 < ref + 2) return null;
  const laneFarmOk = ok(me.lane10, R(c, 'lane10')) && me.lane10 >= R(c, 'lane10') * 0.9;
  return laneFarmOk
    ? tip('lane_deaths_farmok', 'lane_deaths', 'Линия', 'bad', 75, `${me.d10} ${plural(me.d10, 'смерть', 'смерти', 'смертей')} на линии при нормальном фарме`,
      `Души с линии ты собираешь не хуже топов, но умираешь: у топов к 10:00 обычно ${D1(ref)} ${plural(ref, 'смерть', 'смерти', 'смертей')}.`,
      'Фарм есть — значит, проблема в позиции. Не подходи к врагу на расстояние его способностей, когда они у него готовы.')
    : tip('lane_deaths_both', 'lane_deaths', 'Линия', 'bad', 80, `${me.d10} ${plural(me.d10, 'смерть', 'смерти', 'смертей')} до 10:00 и потерянный фарм`,
      `Топы на ${c.heroName(me.hero)} к 10:00 умирают около ${D1(ref)} ${times(ref)}. Каждая твоя смерть отдала врагу души и пару волн, пока ты возрождался.`,
      'Пока линия тяжёлая, играй от своей башни и добивай только безопасных крипов. Жди помощи команды, а не пытайся выиграть размен в одиночку.');
});

rule((c) => {
  const { me } = c;
  if (!ok(me.nw10, me.laneFoeNw10) || !me.laneFoes.length) return null;
  const foes = me.laneFoes.map(c.heroName).join(' и ');
  const r = me.nw10 / me.laneFoeNw10;
  if (r >= 1.15) {
    return tip('lane_vs_won', 'lane_vs', 'Линия', 'good', 20, `Линия выиграна против ${foes}`,
      `К 10:00 у тебя ${N(me.nw10)} душ, у противника по линии — ${N(me.laneFoeNw10)} (+${Math.round((r - 1) * 100)}%).`,
      'Выигранную линию нужно превратить в пользу: дави вражеского стража или иди помочь на соседнюю линию, где наши проигрывают.');
  }
  if (r <= 0.85) {
    return tip('lane_vs_lost', 'lane_vs', 'Линия', 'warn', 58, `Линия проиграна против ${foes}`,
      `К 10:00 у тебя ${N(me.nw10)} душ, у противника по линии — ${N(me.laneFoeNw10)} (${Math.round((r - 1) * 100)}%).`,
      `Открой в «Про-игроках» матчи топов против ${foes}: против неудобного противника топы обычно фармят под своей башней и ждут помощи, а не дерутся.`);
  }
  return null;
});

rule((c) => {
  const { me } = c;
  const ref = R(c, 'dmgLane');
  if (!ok(me.dmgLane, ref, me.d10) || ref < 50) return null;
  const dRef = R(c, 'd10') || 0;
  if (me.dmgLane < ref * 0.6 && me.d10 <= dRef) {
    return tip('lane_passive', 'lane_dmg', 'Линия', 'warn', 50, 'Слишком пассивная линия',
      `За первые 10 минут ты наносил ${N(me.dmgLane)} урона по героям в минуту, топы на ${c.heroName(me.hero)} — ${N(ref)}. Ты не умирал, но и врага не наказывал.`,
      'Стреляй по врагу, когда он подходит добить крипа: в этот момент он стоит на месте и отвлечён. Так ты сбиваешь ему фарм и заставляешь лечиться.');
  }
  if (me.dmgLane >= ref && me.d10 >= dRef + 1) {
    return tip('lane_aggro_cost', 'lane_dmg', 'Линия', 'warn', 52, 'Агрессивная линия, но ценой смертей',
      `Урона по героям у тебя на линии даже больше, чем у топов (${N(me.dmgLane)} против ${N(ref)} в минуту), но ${me.d10} ${plural(me.d10, 'смерть', 'смерти', 'смертей')} до 10:00 съели эту выгоду.`,
      'Нанести урон — ещё не выиграть размен. Дерись, когда у тебя больше здоровья, чем у врага, и отходи сразу после своей атаки.');
  }
  return null;
});

